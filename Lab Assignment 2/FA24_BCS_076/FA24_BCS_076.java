/* This game is basically a simplification of Yard Sale model which is 
used by economists to model how wealth gets accumulated in fewer hands. 
In the original model one player gets all the wealth and other players 
are eliminated from the game one by one. This is how a capitalist society 
works, i.e wealth gets accumulated in fewer and fewer hands. Here is 
wealth distribution in America (generated by ChatGPT) for the last 10 years. 
Year	Top 1% (≈)	Next 19% (≈)	Bottom 80% (≈)
2015		29.0%	51.0%			20.0%
2016		30.0%	50.0%			20.0%
2017		30.8%	49.2%			20.0%
2018		31.0%	49.0%			20.0%
2019		32.0%	48.0%			20.0%
2020		31.0%	49.0%			20.0%
2021		33.0%	47.0%			20.0%
2022		32.0%	48.0%			20.0%
2023		33.5%	46.5%			20.0%
2024		30.8%	49.2%			20.0%
I have modified model by introducing the concept of Zakat in it. 
If you run it without zakat with (5 1000 200 0) as command line parameters 
the game will terminate after approximately 90 rounds, with all the 
wealth accumulated in one player. But if you turn on the zakat option 
(5 1000 200 1)the game will never terminate. As I said in the first line it is a 
simplification and as such the zakat rules are not enforced as described 
in sharia, i.e this is not a sharia compliant game. Its purpose is basically to 
make people think.
newFixedThreadPool(n):
- Always uses at most n threads, which stay alive and are reused.
- Extra tasks wait in an unbounded queue until a thread is free.
Pros: predictable resource usage, no thread-creation cost per task,
      good for CPU-bound work when n = number of cores (less context switching).
Cons: the queue can grow very large under heavy load (memory), threads sit
      idle when there is no work, and blocking tasks can hold up the others.

newCachedThreadPool():
- Creates a new thread whenever no idle thread is available (no upper limit);
idle threads are removed after 60 seconds.
Pros: scales automatically for many short-lived or bursty tasks, low latency,
      frees resources when idle.
Cons: no limit on threads, so a flood of tasks can create thousands of threads
      and cause OutOfMemoryError and heavy context switching; poor for
      long-running CPU-bound work.

Conclusion: the games are short CPU-bound tasks, so a fixed pool sized to the
number of cores is the better choice here.
*/

import java.util.Random;
import java.util.List;
import java.util.ArrayList;
import java.util.concurrent.Executors;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Future;

public class FA24_BCS_076 {

    static int[] balances;                       // balance of every player
    static Random rand = new Random();           // used for opponent and coin flip

    public static void main(String[] args) throws Exception {
        if (args.length != 4) {
            System.out.println("Please provide number_of_Players initial_balance cut_Off_Value zakat_on_off");
            System.exit(1);
        }

        int numPlayers = Integer.parseInt(args[0]);
        int initialBalance = Integer.parseInt(args[1]);
        int cutOffValue = Integer.parseInt(args[2]);
        int zakat = Integer.parseInt(args[3]);
        int rounds = 0;

        // Number of threads = number of CPU cores
        int numOfThreads = Runtime.getRuntime().availableProcessors();
        System.out.println("The machine that I am running on has " + numOfThreads + " cores");

        // Initialize the balances of each player
        balances = new int[numPlayers];
        for (int i = 0; i < numPlayers; i++) {
            balances[i] = initialBalance;
        }

        // Create the fixed thread pool
        ExecutorService pool = Executors.newFixedThreadPool(numOfThreads);

        while (numPlayers > 1) {
            System.out.println("This is round# " + (rounds + 1));

            // Keeps track of the games of this round so we can wait for them
            List<Future<?>> games = new ArrayList<>();

            for (int i = 0; i < numPlayers; i++) {

                // Skip eliminated players in case of non zakat version
                if (balances[i] < cutOffValue && zakat == 0) {
                    continue;
                }

                // Find a valid opponent
                int opponent;
                do {
                    opponent = rand.nextInt(numPlayers);
                } while (opponent == i || balances[opponent] < cutOffValue);

                // Copies are needed because the lambda only accepts final variables
                final int p1 = i;
                final int p2 = opponent;

                // Give this game to a thread from the pool
                games.add(pool.submit(() -> playGame(p1, p2)));

                // Small delay between creation of games (as in the sample output)
                Thread.sleep(100);
            }

            // Wait until ALL games of this round are finished
            for (Future<?> game : games) {
                game.get();
            }
            rounds++;

            if (zakat == 1) {
                // Find a player with balance <= cutoff (the poor)
                int rich = 0, max = 0, poor = 0;
                boolean foundPoor = false;
                for (int i = 0; i < numPlayers; i++) {
                    if (balances[i] <= cutOffValue) {
                        foundPoor = true;
                        poor = i;
                        break;
                    }
                }
                // Transfer 2.5% of the richest player's wealth to the poor player
                if (foundPoor) {
                    for (int i = 0; i < numPlayers; i++) {
                        if (balances[i] > max) {
                            max = balances[i];
                            rich = i;
                        }
                    }
                    int calcZakat = (int) (balances[rich] * .025);
                    balances[poor] = balances[poor] + calcZakat;
                    balances[rich] = balances[rich] - calcZakat;
                    System.out.println("Zakat = " + calcZakat + " was transferred from Player "
                            + rich + " to " + poor);
                }
            } else {
                // Eliminate players below the cutoff value
                int numRemainingPlayers = 0;
                for (int i = 0; i < numPlayers; i++) {
                    if (balances[i] >= cutOffValue) {
                        balances[numRemainingPlayers] = balances[i];
                        numRemainingPlayers++;
                    } else {
                        System.out.println("Player " + i + " eliminated with balance " + balances[i]);
                    }
                }
                numPlayers = numRemainingPlayers;
            }
        }

        System.out.printf("Game finished after %d rounds\n", rounds);
        pool.shutdown();   // stop the pool, otherwise the program will not exit
    }

    // One game between two players, executed by a pool thread
    static void playGame(int a, int b) {
        // Name of the thread running this game and the current time
        Thread currentThread = Thread.currentThread();
        String threadName = currentThread.getName();
        System.out.println("Thread " + threadName + " is going to start game at "
                + System.currentTimeMillis());

        // Only one thread at a time may change the balances
        synchronized (balances) {
            int betAmount = Math.min(balances[a], balances[b]) / 5;

            // Flip the coin and determine the winner
            if (rand.nextBoolean()) {
                balances[a] += betAmount;
                balances[b] -= betAmount;
            } else {
                balances[a] -= betAmount;
                balances[b] += betAmount;
            }

            System.out.println("Bet result : player " + a + " has " + balances[a]
                    + " vs " + b + " has " + balances[b]);
        }
    }
}
